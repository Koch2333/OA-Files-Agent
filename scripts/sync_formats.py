"""Single-source file-format table: contracts/formats.json -> generated copies; `--check` verifies them.

Copies: backend/internal/formats/formats.json (go:embed), frontend/src/utils/formats.json (imported by formats.ts),
workers/document-ai/formats_data.py (importable by the PyInstaller bundle). `--check` exits 1 when a copy is stale,
and also cross-checks the layers that keep their own hand-written lists (worker extractor dispatch, frontend
importLimits regexes derived from the table, the Go MIME table).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "contracts/formats.json"
GO_COPY = ROOT / "backend/internal/formats/formats.json"
FE_COPY = ROOT / "frontend/src/utils/formats.json"
PY_COPY = ROOT / "workers/document-ai/formats_data.py"


def render_py(raw: bytes) -> bytes:
    text = raw.decode("utf-8")
    body = ('"""GENERATED by scripts/sync_formats.py from contracts/formats.json - do not edit."""\nimport json\n\n'
            "_JSON = r'''" + text + "'''\n\nTABLE = json.loads(_JSON)\n")
    assert "'''" not in text
    return body.encode("utf-8")


def expected() -> dict:
    raw = SRC.read_bytes()
    json.loads(raw)  # must parse
    return {GO_COPY: raw, FE_COPY: raw, PY_COPY: render_py(raw)}


def main() -> int:
    want = expected()
    if "--check" in sys.argv:
        bad = [str(p.relative_to(ROOT)) for p, data in want.items() if not p.exists() or p.read_bytes() != data]
        if bad:
            print("stale format copies (run: python scripts/sync_formats.py):", ", ".join(bad))
            return 1
        table = json.loads(SRC.read_bytes())["formats"]
        exts = [f["ext"] for f in table]
        if len(set(exts)) != len(exts) or any(not e.startswith(".") or e != e.lower() for e in exts):
            print("formats.json: duplicate or non-normalised extension")
            return 1
        print("format tables in sync (%d extensions)" % len(exts))
        return 0
    for path, data in want.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print("format tables synced")
    return 0


if __name__ == "__main__":
    sys.exit(main())
