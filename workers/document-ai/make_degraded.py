"""Generate degraded variants of the OCR samples into tests/samples/degraded/ plus manifest.json.

Run with the worker venv:  .venv\\Scripts\\python.exe make_degraded.py
Existing fixtures in tests/samples/ are only read, never modified. Output is deterministic (fixed seed).
"""
import json
import os

import cv2
import numpy as np
import pymupdf as fitz

HERE = os.path.dirname(os.path.abspath(__file__))
SAMPLES = os.path.normpath(os.path.join(HERE, "..", "..", "tests", "samples"))
OUT = os.path.join(SAMPLES, "degraded")

# (output stem, source file) - keywords come from the source's entry in tests/samples/manifest.json
SOURCES = [
    ("purchase_photo", "采购申请单_拍照.png"),
    ("training_notice", "人事部_入职培训通知.jpg"),
    ("labor_contract_scan", "劳动合同续签_扫描件.pdf"),
    ("finance_scan", "scan_20260520_001.pdf"),
]


def load(name):
    path = os.path.join(SAMPLES, name)
    if name.lower().endswith(".pdf"):
        doc = fitz.open(path)
        try:
            data = doc[0].get_pixmap(dpi=200).tobytes("png")
        finally:
            doc.close()
    else:
        with open(path, "rb") as f:
            data = f.read()
    return cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_COLOR)


def rotate_expand(img, angle):
    h, w = img.shape[:2]
    m = cv2.getRotationMatrix2D((w / 2.0, h / 2.0), angle, 1.0)
    cos, sin = abs(m[0, 0]), abs(m[0, 1])
    nw, nh = int(h * sin + w * cos), int(h * cos + w * sin)
    m[0, 2] += nw / 2.0 - w / 2.0
    m[1, 2] += nh / 2.0 - h / 2.0
    return cv2.warpAffine(img, m, (nw, nh), flags=cv2.INTER_CUBIC, borderValue=(255, 255, 255))


def low_contrast(img, gain=0.25, offset=150):
    gray = img.astype(np.float32)
    return np.clip(gray * gain + offset, 0, 255).astype(np.uint8)  # text/background squeezed into ~[150, 215]


def noise_blur(img, sigma=38, blur=1.6):
    rng = np.random.default_rng(7)
    noisy = img.astype(np.float32) + rng.normal(0, sigma, img.shape)
    noisy = np.clip(noisy, 0, 255).astype(np.uint8)
    return cv2.GaussianBlur(noisy, (0, 0), blur)


def small_photo(img, scale=0.35, quality=45):
    h, w = img.shape[:2]
    small = cv2.resize(img, (int(w * scale), int(h * scale)), interpolation=cv2.INTER_AREA)
    ok, buf = cv2.imencode(".jpg", small, [cv2.IMWRITE_JPEG_QUALITY, quality])
    return cv2.imdecode(buf, cv2.IMREAD_COLOR)


DEGRADATIONS = {
    "rot90": lambda im: cv2.rotate(im, cv2.ROTATE_90_CLOCKWISE),
    "rot180": lambda im: cv2.rotate(im, cv2.ROTATE_180),
    "skew8": lambda im: rotate_expand(im, 8.0),
    "low_contrast": low_contrast,
    "noise_blur": noise_blur,
    "small_font": small_photo,
    # harsher variants (the moderate ones above turned out to be easy for the default profile)
    "low_contrast_extreme": lambda im: low_contrast(im, 0.08, 205),
    "noise_heavy": lambda im: noise_blur(im, 75, 2.2),
    "small_font_tiny": lambda im: small_photo(im, 0.2, 30),
    "rot90_noise": lambda im: noise_blur(cv2.rotate(im, cv2.ROTATE_90_CLOCKWISE), 55, 1.8),
    "skew14_noise": lambda im: noise_blur(rotate_expand(im, 14.0), 55, 1.8),
}


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(SAMPLES, "manifest.json"), encoding="utf-8") as f:
        source_entries = {e["file"]: e for e in json.load(f)["files"]}
    files = []
    for stem, source in SOURCES:
        base = load(source)
        keywords = source_entries[source]["keywords"]
        for name, fn in DEGRADATIONS.items():
            out_name = "%s_%s.png" % (stem, name)
            ok, buf = cv2.imencode(".png", fn(base))
            with open(os.path.join(OUT, out_name), "wb") as f:
                f.write(buf.tobytes())
            files.append({"file": out_name, "source": source, "degradation": name, "keywords": keywords})
    with open(os.path.join(OUT, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump({"note": "Degraded variants generated by workers/document-ai/make_degraded.py", "files": files},
                  f, ensure_ascii=False, indent=2)
    print("wrote %d files to %s" % (len(files), OUT))


if __name__ == "__main__":
    main()
