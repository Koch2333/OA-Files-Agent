// Generates src/components/iconGlyphs.ts from the Material Symbols (Outlined, 400) SVGs in node_modules.
// Reads the glyph names from src/components/iconMap.ts (values of NAMES, plus the FILLED list), so only
// icons that are actually mapped ship. Run: npm run gen:icons
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'node_modules/@material-symbols/svg-400/outlined')
const src = fs.readFileSync(path.join(root, 'src/components/iconMap.ts'), 'utf8')
const namesBlock = /const NAMES[^{]*\{([\s\S]*?)\n\}/.exec(src)[1]
const names = new Set([...namesBlock.matchAll(/:\s*'([a-z0-9_]+)'/g)].map((m) => m[1]))
const filled = new Set([...(/export const FILLED[^=]*=\s*\[([\s\S]*?)\]/.exec(src)[1]).matchAll(/'([a-z0-9_]+)'/g)].map((m) => m[1]))
names.add('circle')

const read = (file) => {
  const p = path.join(dir, file)
  if (!fs.existsSync(p)) return null
  return /<path d="([^"]+)"/.exec(fs.readFileSync(p, 'utf8'))[1]
}
let out = `// GENERATED by scripts/gen-icons.mjs from @material-symbols/svg-400 (Outlined, weight 400, Apache-2.0). Do not edit.
// Glyph = [outlined path, filled path?], viewBox "0 -960 960 960".
export type Glyph = readonly [string, string?]
export const GLYPHS: Record<string, Glyph> = {
`
let bad = 0
for (const n of [...names].sort()) {
  const o = read(`${n}.svg`)
  if (!o) { console.error(`missing Material Symbol: ${n}`); bad++; continue }
  const f = filled.has(n) ? read(`${n}-fill.svg`) : null
  out += `  ${n}: ['${o}'${f ? `, '${f}'` : ''}],\n`
}
out += '}\n'
if (bad) process.exit(1)
fs.writeFileSync(path.join(root, 'src/components/iconGlyphs.ts'), out)
console.log(`wrote ${names.size} glyphs (${filled.size} filled)`)
